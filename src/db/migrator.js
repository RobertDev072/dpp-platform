const fs = require("fs");
const path = require("path");
const { getPool } = require("../config/db");

// PostgreSQL-migraties (db/migrations, oplopend op bestandsnaam). Elke migratie draait
// in een eigen transactie en wordt op bestandsnaam bijgehouden in dbo.schemamigrations.
// Gebruikt door scripts/migrate.js (lokaal/CI). Het pad is relatief aan de werkmap
// (repo-root), omdat de app-code gebundeld wordt.
function migrationsDir() {
  return process.env.MIGRATIONS_DIR || path.resolve(process.cwd(), "db", "migrations");
}

async function runMigrations({ log = () => {} } = {}) {
  const pool = await getPool();
  await pool.query(`
    CREATE SCHEMA IF NOT EXISTS dbo;
    CREATE TABLE IF NOT EXISTS dbo.schemamigrations (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      filename varchar(255) NOT NULL UNIQUE,
      applied_at timestamptz NOT NULL DEFAULT now()
    );
  `);
  const appliedResult = await pool.query("SELECT filename FROM dbo.schemamigrations");
  const applied = new Set(appliedResult.rows.map((row) => row.filename));

  const dir = migrationsDir();
  const files = fs.readdirSync(dir).filter((file) => file.endsWith(".sql")).sort();
  const newlyApplied = [];

  for (const file of files) {
    if (applied.has(file)) {
      log(`↷ overslaan (al toegepast): ${file}`);
      continue;
    }
    const migrationSql = fs.readFileSync(path.join(dir, file), "utf8");
    const client = await pool.connect();
    try {
      await client.query("BEGIN");
      await client.query(migrationSql);
      await client.query("INSERT INTO dbo.schemamigrations (filename) VALUES ($1)", [file]);
      await client.query("COMMIT");
      newlyApplied.push(file);
      log(`✅ toegepast: ${file}`);
    } catch (error) {
      await client.query("ROLLBACK");
      throw new Error(`Migratie mislukt (${file}): ${error.message}`);
    } finally {
      client.release();
    }
  }
  return { applied: newlyApplied, total: files.length };
}

module.exports = { runMigrations, migrationsDir };
