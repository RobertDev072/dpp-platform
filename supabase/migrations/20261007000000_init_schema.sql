  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  taken_at timestamptz NOT NULL DEFAULT now(),
  database_size_bytes bigint NULL,
  database_max_bytes bigint NULL,
  blob_storage_bytes bigint NULL,
  blob_count integer NULL,
  partner_count integer NOT NULL DEFAULT 0,
  company_count integer NOT NULL DEFAULT 0,
  user_count integer NOT NULL DEFAULT 0,
  active_user_count integer NOT NULL DEFAULT 0,
  product_count integer NOT NULL DEFAULT 0,
  document_count integer NOT NULL DEFAULT 0,
  audit_log_count integer NOT NULL DEFAULT 0,
  scan_event_count integer NOT NULL DEFAULT 0,
  invite_count integer NOT NULL DEFAULT 0,
  -- JSON: per-tabel rijen/bytes en per-bucket opslagverdeling.
  table_stats text NULL,
  blob_stats text NULL
);
CREATE INDEX IF NOT EXISTS ix_systemmetricssnapshots_taken_at ON dbo.systemmetricssnapshots (taken_at);

CREATE TABLE IF NOT EXISTS dbo.systemrequestmetricshourly (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bucket_start timestamptz NOT NULL,
  -- scope: 'api' | 'public' (publieke paspoortpagina's) | 'page' (overige pagina's)
  scope varchar(20) NOT NULL,
  -- route is een patroon ('/api/products/:id'), nooit een concrete URL met id's.
