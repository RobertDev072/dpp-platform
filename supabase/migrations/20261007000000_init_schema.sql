  duration_max_ms integer NOT NULL DEFAULT 0,
  p50_ms integer NULL,
  p95_ms integer NULL,
  p99_ms integer NULL
);
CREATE INDEX IF NOT EXISTS ix_systemrequestmetricshourly_bucket ON dbo.systemrequestmetricshourly (bucket_start);

-- Tweede slot naast het niet-ontsloten schema: RLS aan zonder policies, en geen
-- rechten voor de publieke Supabase-rollen. De app (tabeleigenaar) merkt hier niets van.
DO $$
DECLARE
  t record;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'dbo' LOOP
    EXECUTE format('ALTER TABLE dbo.%I ENABLE ROW LEVEL SECURITY', t.tablename);
  END LOOP;

  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON SCHEMA dbo FROM anon, authenticated;
    REVOKE ALL ON ALL TABLES IN SCHEMA dbo FROM anon, authenticated;
  END IF;
END $$;

-- Privé-buckets voor uploads (alleen op Supabase; een kale lokale Postgres heeft
-- geen storage-schema). Limieten zijn gelijk aan de API-limieten, zodat ook een
-- directe upload via een signed upload-URL ze niet kan omzeilen.
DO $$
BEGIN
  IF to_regclass('storage.buckets') IS NOT NULL THEN
    INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    VALUES
      ('product-images', 'product-images', false, 5242880,
        ARRAY['image/jpeg', 'image/png', 'image/webp', 'image/gif']),
      ('product-documents', 'product-documents', false, 10485760,
        ARRAY['application/pdf', 'image/jpeg', 'image/png', 'image/svg+xml', 'image/webp'])
    ON CONFLICT (id) DO UPDATE
      SET public = false,
          file_size_limit = EXCLUDED.file_size_limit,
          allowed_mime_types = EXCLUDED.allowed_mime_types;
  END IF;
END $$;
