-- Zuinig en robuust bij grote aantallen (additief, idempotent).
--
-- 1. Bedrijfslogo en profielfoto in de objectopslag (R2) i.p.v. als data-URI in de
--    database: kleinere database, en het logo hoeft niet meer bij elk verzoek mee
--    (de sessiecontrole las het volledige logo bij elke API-aanroep).
ALTER TABLE dbo.companies ADD COLUMN IF NOT EXISTS logo_blob_name varchar(300) NULL;
ALTER TABLE dbo.users ADD COLUMN IF NOT EXISTS avatar_blob_name varchar(300) NULL;

-- 2. Scans per dag. Losse scanregels (dbo.scanevents) worden na 90 dagen opgeruimd;
--    de aantallen blijven bewaard in dbo.scandaily. Tot en met de datum in
--    dbo.scanrollup zijn alle dagen samengevat; daarna tellen de losse regels.
--    De samenvatting loopt drie dagen achter, omdat gebundelde scans van de
--    Cloudflare Worker tot twee dagen na het scannen kunnen binnenkomen.
CREATE TABLE IF NOT EXISTS dbo.scandaily (
  product_id integer NOT NULL REFERENCES dbo.products(id),
  day date NOT NULL,
  scans integer NOT NULL,
  last_scan_at timestamptz NOT NULL,
  PRIMARY KEY (product_id, day)
);
CREATE INDEX IF NOT EXISTS ix_scandaily_day ON dbo.scandaily (day);

CREATE TABLE IF NOT EXISTS dbo.scanrollup (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  rolled_up_through date NOT NULL DEFAULT DATE '1970-01-01'
);
INSERT INTO dbo.scanrollup (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- Eén bron voor alle scanstatistieken: samengevatte dagen + losse regels erna.
CREATE OR REPLACE VIEW dbo.scandays AS
  SELECT d.product_id, d.day, d.scans::bigint AS scans, d.last_scan_at
  FROM dbo.scandaily d, dbo.scanrollup r
  WHERE d.day <= r.rolled_up_through
  UNION ALL
  SELECT s.product_id, (s.scanned_at AT TIME ZONE 'UTC')::date AS day, COUNT(*)::bigint AS scans, MAX(s.scanned_at) AS last_scan_at
  FROM dbo.scanevents s, dbo.scanrollup r
  WHERE s.scanned_at >= ((r.rolled_up_through + 1)::timestamp AT TIME ZONE 'UTC')
  GROUP BY s.product_id, (s.scanned_at AT TIME ZONE 'UTC')::date;

-- 3. Noodkopie van elk openbaar paspoort (statische HTML + JSON in R2), zodat gedrukte
--    QR-codes ook werken als de server onbereikbaar is (de Cloudflare Worker toont dan
--    de kopie). Wachtrij: paspoorten waarvan de kopie ververst moet worden.
CREATE TABLE IF NOT EXISTS dbo.passportsnapshots (
  product_id integer PRIMARY KEY REFERENCES dbo.products(id),
  public_id uuid NOT NULL,
  content_sha256 char(64) NOT NULL,
  written_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS dbo.passportsnapshotqueue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL,
  queued_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_passportsnapshotqueue_public_id ON dbo.passportsnapshotqueue (public_id);
