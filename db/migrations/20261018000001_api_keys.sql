-- API-sleutels voor externe systemen (B2B-API /api/v1). Per bedrijf; alleen een SHA-256
-- van de sleutel wordt bewaard (de sleutel zelf is één keer zichtbaar bij aanmaken).
CREATE TABLE IF NOT EXISTS dbo.apikeys (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id integer NOT NULL REFERENCES dbo.companies(id) ON DELETE CASCADE,
  name varchar(100) NOT NULL,
  key_prefix varchar(24) NOT NULL,
  key_hash char(64) NOT NULL,
  scopes varchar(50) NOT NULL DEFAULT 'read',
  created_by integer NULL REFERENCES dbo.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz NULL,
  expires_at timestamptz NULL,
  revoked_at timestamptz NULL,
  CONSTRAINT uq_apikeys_hash UNIQUE (key_hash),
  CONSTRAINT chk_apikeys_scopes CHECK (scopes IN ('read', 'read write'))
);
CREATE INDEX IF NOT EXISTS ix_apikeys_company ON dbo.apikeys (company_id);

-- Zoeken op GTIN (ReadDPPByProductId) over alle bedrijven, alleen openbare paspoorten.
CREATE INDEX IF NOT EXISTS ix_products_gtin_public ON dbo.products (gtin) WHERE gtin IS NOT NULL AND public_id IS NOT NULL;
