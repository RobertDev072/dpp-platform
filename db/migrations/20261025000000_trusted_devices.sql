-- Vertrouwde apparaten: na een geslaagde tweestapsverificatie met "Onthoud deze computer"
-- slaat de gebruiker 30 dagen de code over op dát apparaat (het wachtwoord blijft altijd
-- nodig). Alleen een SHA-256 van het apparaattoken wordt bewaard. Vervalt bij een
-- wachtwoordwijziging, het uit- of opnieuw instellen van MFA en via "Alle computers vergeten".
CREATE TABLE IF NOT EXISTS dbo.trusteddevices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES dbo.users(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL,
  label varchar(200) NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz NULL,
  expires_at timestamptz NOT NULL,
  CONSTRAINT uq_trusteddevices_hash UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS ix_trusteddevices_user ON dbo.trusteddevices (user_id);
