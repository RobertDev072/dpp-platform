-- Toegang per niveau en registratiestatus (EU DPP-register).
--
-- 1. Documenten: naast openbaar (is_public) een beperkte zichtbaarheid voor externe
--    partijen: 'professional' (reparateurs, recyclers; ook autoriteiten) of 'authority'
--    (markttoezicht, aangemelde instanties, Commissie). NULL = alleen het eigen bedrijf.
-- 2. Toegangstokens die een bedrijf aan zulke partijen geeft. Alleen een SHA-256 van het
--    token wordt bewaard. company_id NULL = geldig voor alle bedrijven (alleen de
--    Platform Owner, voor autoriteiten).
-- 3. Registratiestatus per paspoort zoals het register die teruggeeft: registratie-URI,
--    correlation ID, foutcode, de UPI en de paspoortversie waarop de registratie slaat.

ALTER TABLE dbo.documents ADD COLUMN IF NOT EXISTS access_level varchar(20) NULL;
ALTER TABLE dbo.documents DROP CONSTRAINT IF EXISTS chk_documents_access_level;
ALTER TABLE dbo.documents ADD CONSTRAINT chk_documents_access_level CHECK (access_level IS NULL OR access_level IN ('professional', 'authority'));

CREATE TABLE IF NOT EXISTS dbo.dppaccesstokens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id integer NULL REFERENCES dbo.companies(id) ON DELETE CASCADE,
  access_level varchar(20) NOT NULL,
  name varchar(100) NOT NULL,
  token_prefix varchar(24) NOT NULL,
  token_hash char(64) NOT NULL,
  created_by integer NULL REFERENCES dbo.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz NULL,
  expires_at timestamptz NULL,
  revoked_at timestamptz NULL,
  CONSTRAINT uq_dppaccesstokens_hash UNIQUE (token_hash),
  CONSTRAINT chk_dppaccesstokens_level CHECK (access_level IN ('professional', 'authority'))
);
CREATE INDEX IF NOT EXISTS ix_dppaccesstokens_company ON dbo.dppaccesstokens (company_id);

ALTER TABLE dbo.dppregistrations ADD COLUMN IF NOT EXISTS upi varchar(500) NULL;
ALTER TABLE dbo.dppregistrations ADD COLUMN IF NOT EXISTS version_number integer NULL;
ALTER TABLE dbo.dppregistrations ADD COLUMN IF NOT EXISTS registry_uri varchar(500) NULL;
ALTER TABLE dbo.dppregistrations ADD COLUMN IF NOT EXISTS correlation_id varchar(200) NULL;
ALTER TABLE dbo.dppregistrations ADD COLUMN IF NOT EXISTS error_code varchar(100) NULL;
ALTER TABLE dbo.dppregistrations ADD COLUMN IF NOT EXISTS submitted_at timestamptz NULL;
ALTER TABLE dbo.dppregistrations ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE dbo.dppregistrations DROP CONSTRAINT IF EXISTS chk_dppregistrations_status;
ALTER TABLE dbo.dppregistrations ADD CONSTRAINT chk_dppregistrations_status
  CHECK (status IN ('queued', 'submitted', 'registered', 'rejected', 'failed'));
