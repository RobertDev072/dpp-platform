-- Logboek van opvragingen met een toegangstoken (professional/authority): welk token wanneer
-- welk paspoort of document opvroeg. Tokenhouders zijn vaak personen (AVG): alleen het
-- minimum (geen IP-adres, geen browser), en na 365 dagen automatisch gewist (zie
-- src/monitoring/collectors.js → pruneOldMetrics).
CREATE TABLE IF NOT EXISTS dbo.dppaccesslog (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_id integer NOT NULL REFERENCES dbo.dppaccesstokens(id) ON DELETE CASCADE,
  public_id uuid NOT NULL,
  resource varchar(20) NOT NULL,
  document_id integer NULL,
  accessed_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_dppaccesslog_resource CHECK (resource IN ('passport', 'version', 'document'))
);
CREATE INDEX IF NOT EXISTS ix_dppaccesslog_token ON dbo.dppaccesslog (token_id, accessed_at DESC);
CREATE INDEX IF NOT EXISTS ix_dppaccesslog_time ON dbo.dppaccesslog (accessed_at);
