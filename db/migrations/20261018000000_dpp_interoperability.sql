-- DPP-interoperabiliteit (EN 18219/18223-richting): identificatie van de marktdeelnemer,
-- vestiging, inhoudsspecificaties, taal en vertalingen. Alleen toevoegingen; bestaande
-- velden en paspoort-URL's blijven ongewijzigd.

-- Marktdeelnemer (economic operator): erkende identificatie van het bedrijf.
ALTER TABLE dbo.companies ADD COLUMN IF NOT EXISTS economic_operator_id varchar(100) NULL;
ALTER TABLE dbo.companies ADD COLUMN IF NOT EXISTS economic_operator_id_scheme varchar(20) NULL;
DO $$ BEGIN
  ALTER TABLE dbo.companies ADD CONSTRAINT chk_companies_operator_scheme
    CHECK (economic_operator_id_scheme IS NULL OR economic_operator_id_scheme IN ('lei', 'gln', 'eori', 'vat', 'duns', 'kvk', 'other'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- Per product: vestiging (facility, bijv. GLN), inhoudsspecificaties (verwijzingen naar
-- de toepasselijke wetgeving/normen) als JSON-array, en de taal van de basisteksten.
ALTER TABLE dbo.products ADD COLUMN IF NOT EXISTS facility_id varchar(100) NULL;
ALTER TABLE dbo.products ADD COLUMN IF NOT EXISTS content_specification_ids text NULL;
ALTER TABLE dbo.products ADD COLUMN IF NOT EXISTS language varchar(12) NOT NULL DEFAULT 'nl-NL';
DO $$ BEGIN
  ALTER TABLE dbo.products ADD CONSTRAINT chk_products_language CHECK (language ~ '^[a-z]{2,3}(-[A-Z]{2})?$');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- Vertalingen van de publieke teksten (MultiLanguage). Eén rij per taal.
CREATE TABLE IF NOT EXISTS dbo.producttranslations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES dbo.products(id) ON DELETE CASCADE,
  language varchar(12) NOT NULL,
  name varchar(200) NULL,
  description text NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_producttranslations_language CHECK (language ~ '^[a-z]{2,3}(-[A-Z]{2})?$')
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_producttranslations_product_language ON dbo.producttranslations (product_id, language);

-- Permanentie: een eenmaal toegekende public_id (de gedrukte QR-sleutel) kan nooit
-- meer veranderen of verdwijnen. De code deed dit al nooit; nu weigert ook de database het.
CREATE OR REPLACE FUNCTION dbo.products_public_id_immutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF OLD.public_id IS NOT NULL AND NEW.public_id IS DISTINCT FROM OLD.public_id THEN
    RAISE EXCEPTION 'public_id van product % is permanent en kan niet worden gewijzigd', OLD.id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_products_public_id_immutable ON dbo.products;
CREATE TRIGGER trg_products_public_id_immutable
  BEFORE UPDATE OF public_id ON dbo.products
  FOR EACH ROW EXECUTE FUNCTION dbo.products_public_id_immutable();
