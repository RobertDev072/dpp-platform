-- Paspoorten op batch- en itemniveau (EN 18219-richting: model, batch, item). Een batch-
-- of itempaspoort heeft een eigen permanente id (eigen QR-code), en neemt de product-
-- gegevens over van het modelpaspoort. Alleen toevoegingen.

ALTER TABLE dbo.productbatches ADD COLUMN IF NOT EXISTS public_id uuid NULL;
ALTER TABLE dbo.productbatches ADD COLUMN IF NOT EXISTS alias_written_at timestamptz NULL;
UPDATE dbo.productbatches SET public_id = gen_random_uuid() WHERE public_id IS NULL;
ALTER TABLE dbo.productbatches ALTER COLUMN public_id SET DEFAULT gen_random_uuid();
ALTER TABLE dbo.productbatches ALTER COLUMN public_id SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_productbatches_public_id ON dbo.productbatches (public_id);

-- Individuele exemplaren (serienummers). Serienummer volgens GS1 AI 21: max. 20 tekens.
CREATE TABLE IF NOT EXISTS dbo.productitems (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES dbo.products(id),
  company_id integer NOT NULL REFERENCES dbo.companies(id),
  batch_id integer NULL REFERENCES dbo.productbatches(id),
  serial_number varchar(20) NOT NULL,
  public_id uuid NOT NULL DEFAULT gen_random_uuid(),
  status varchar(20) NOT NULL DEFAULT 'active',
  alias_written_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_productitems_public_id UNIQUE (public_id),
  CONSTRAINT uq_productitems_serial UNIQUE (product_id, serial_number),
  CONSTRAINT chk_productitems_status CHECK (status IN ('active', 'archived'))
);
CREATE INDEX IF NOT EXISTS ix_productitems_product ON dbo.productitems (product_id, id);
CREATE INDEX IF NOT EXISTS ix_productitems_alias_pending ON dbo.productitems (id) WHERE alias_written_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_productbatches_alias_pending ON dbo.productbatches (id) WHERE alias_written_at IS NULL;

-- Eén opzoekpunt voor elke paspoort-id (QR-sleutel), ongeacht het niveau.
CREATE OR REPLACE VIEW dbo.passportids AS
  SELECT p.public_id, p.id AS product_id, 'model'::text AS granularity, NULL::integer AS batch_id, NULL::integer AS item_id
  FROM dbo.products p WHERE p.public_id IS NOT NULL
  UNION ALL
  SELECT b.public_id, b.product_id, 'batch', b.id, NULL FROM dbo.productbatches b
  UNION ALL
  SELECT i.public_id, i.product_id, 'item', i.batch_id, i.id FROM dbo.productitems i;

-- Permanentie, zoals bij producten: een batch- of item-id verandert nooit.
CREATE OR REPLACE FUNCTION dbo.instance_public_id_immutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.public_id IS DISTINCT FROM OLD.public_id THEN
    RAISE EXCEPTION 'public_id is permanent en kan niet worden gewijzigd' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_productbatches_public_id_immutable ON dbo.productbatches;
CREATE TRIGGER trg_productbatches_public_id_immutable
  BEFORE UPDATE OF public_id ON dbo.productbatches
  FOR EACH ROW EXECUTE FUNCTION dbo.instance_public_id_immutable();
DROP TRIGGER IF EXISTS trg_productitems_public_id_immutable ON dbo.productitems;
CREATE TRIGGER trg_productitems_public_id_immutable
  BEFORE UPDATE OF public_id ON dbo.productitems
  FOR EACH ROW EXECUTE FUNCTION dbo.instance_public_id_immutable();
