-- Wachtrij voor het verversen van de Cloudflare-cache (publieke paspoorten op het QR-domein).
-- De app heeft geen internettoegang; de Cloudflare Worker haalt deze rijen elke minuut op
-- via /api/edge/sync, ververst de cache en bevestigt daarna (ack), waarna ze verdwijnen.
CREATE TABLE IF NOT EXISTS dbo.edgecachepurges (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
